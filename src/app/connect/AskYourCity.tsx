"use client";
import { useState } from "react";
import { LayerTag } from "@/components/ui";

type Source = { ref: string; kind: string; title: string; sourceName: string; sourceType: string; url: string; score: number };
type Answer = { id: string; answer: string; method: string; model: string | null; sufficient: boolean; sources: Source[] };

const EXAMPLES = [
  "Why does my neighbourhood flood?",
  "What have residents reported about flooding in Bumi Waras?",
  "Where can I check weather warnings?",
  "Which planning policies apply to my area?",
  "How do I submit an official complaint?",
  "What accessibility concerns have been reported?",
];

export function AskYourCity({ aiEnabled }: { aiEnabled: boolean }) {
  const [q, setQ] = useState("");
  const [busy, setBusy] = useState(false);
  const [history, setHistory] = useState<(Answer & { q: string; feedback?: boolean })[]>([]);
  const [error, setError] = useState<string | null>(null);

  async function ask(question: string) {
    if (question.trim().length < 4) return;
    setBusy(true);
    setError(null);
    try {
      const res = await fetch("/api/ask", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ question }) });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error);
      setHistory((h) => [{ ...data, q: question }, ...h]);
      setQ("");
    } catch (e) {
      setError(e instanceof Error ? e.message : "Something went wrong");
    } finally {
      setBusy(false);
    }
  }

  async function feedback(id: string, helpful: boolean) {
    await fetch(`/api/ask/${id}/feedback`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ helpful }) });
    setHistory((h) => h.map((x) => (x.id === id ? { ...x, feedback: helpful } : x)));
  }

  return (
    <div className="card">
      <form
        onSubmit={(e) => {
          e.preventDefault();
          ask(q);
        }}
        className="flex flex-col gap-2 sm:flex-row"
      >
        <input className="input" value={q} onChange={(e) => setQ(e.target.value)} placeholder="Ask about flooding, services, planning, transport…" aria-label="Your question" maxLength={500} />
        <button className="btn-primary shrink-0" disabled={busy || q.trim().length < 4}>{busy ? "Searching…" : "Ask"}</button>
      </form>
      <div className="mt-3 flex flex-wrap gap-2">
        {EXAMPLES.map((e) => (
          <button key={e} onClick={() => ask(e)} disabled={busy} className="rounded-full border border-ink/15 px-3 py-1 text-xs hover:bg-ink/5">{e}</button>
        ))}
      </div>
      <p className="mt-3 text-xs text-ink-soft">
        {aiEnabled ? "Answers are generated by a language model using only the retrieved evidence below, with citations." : "No language model is configured, so YouSee shows the most relevant passages from its evidence base directly."}{" "}
        Questions are logged anonymously so we can evaluate answer quality.
      </p>
      {error && <p className="mt-3 text-sm text-rose-deep">{error}</p>}

      <div className="mt-6 space-y-6" aria-live="polite">
        {history.map((h) => (
          <div key={h.id} className="border-t border-ink/10 pt-5">
            <p className="font-semibold">“{h.q}”</p>
            <div className="mt-2 flex flex-wrap gap-2">
              <LayerTag kind="ai">{h.method === "llm" ? `AI answer · ${h.model}` : "Retrieved evidence"}</LayerTag>
              {!h.sufficient && <span className="chip bg-butter">Limited evidence</span>}
            </div>
            <p className="mt-3 whitespace-pre-line text-sm leading-relaxed">{h.answer}</p>
            {h.sources.length > 0 && (
              <details className="mt-3 text-sm">
                <summary className="cursor-pointer font-semibold">Sources used ({h.sources.length})</summary>
                <ul className="mt-2 space-y-1.5">
                  {h.sources.map((s) => (
                    <li key={s.ref} className="flex flex-wrap items-center gap-2">
                      <span className="font-mono text-xs font-bold">[{s.ref}]</span>
                      <LayerTag kind={s.sourceType === "synthetic" ? "synthetic" : s.kind === "contribution" ? "citizen" : s.kind === "insight" ? "insight" : "evidence"}>{s.sourceType}</LayerTag>
                      <a href={s.url} target={s.url.startsWith("http") ? "_blank" : undefined} rel="noreferrer" className="underline">{s.title}</a>
                      <span className="text-xs text-ink-soft">relevance {s.score}</span>
                    </li>
                  ))}
                </ul>
              </details>
            )}
            <div className="mt-3 flex items-center gap-2 text-xs">
              {h.feedback === undefined ? (
                <>
                  <span>Was this helpful?</span>
                  <button className="rounded-full border px-2 py-0.5" onClick={() => feedback(h.id, true)}>Yes</button>
                  <button className="rounded-full border px-2 py-0.5" onClick={() => feedback(h.id, false)}>No</button>
                </>
              ) : (
                <span className="text-ink-soft">Thanks for the feedback.</span>
              )}
            </div>
          </div>
        ))}
      </div>
    </div>
  );
}
